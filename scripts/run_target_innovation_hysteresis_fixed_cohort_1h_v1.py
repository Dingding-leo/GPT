def main() -> int:
    source = gzip.decompress(base64.b85decode("".join(_PAYLOAD)))
    if hashlib.sha256(source).hexdigest() != _SOURCE_SHA256:
        raise RuntimeError("embedded exact strategy reproducer hash mismatch")
    output_dir: Path | None = None
    for index, argument in enumerate(sys.argv[:-1]):
        if argument == "--output-dir":
            output_dir = Path(sys.argv[index + 1])
            break
    if output_dir is not None:
        output_dir.mkdir(parents=True, exist_ok=True)
        path = output_dir / "exact-reproducer.py"
        path.write_bytes(source)
        path.with_name(path.name + ".sha256").write_text(_SOURCE_SHA256 + "\n")
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "reproducer.py"
        path.write_bytes(source)
        runpy.run_path(str(path), run_name="__main__")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
